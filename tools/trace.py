#!/usr/bin/env python3
"""Build the requirements traceability matrix (docs/traceability.md).

Inputs
  tests/requirements.csv   requirement IDs, level, how they are verified, statement
  C results                lines "RESULT,<case>,<req;req>,<PASS|FAIL>,<checks>" from tests/c/test_control
  JUnit XML                from pytest; tests marked @pytest.mark.req("REQ-xx") carry a "req" property

Exit code 1 when
  - any test failed,
  - a requirement that is verified on the host has no test,
  - a test names a requirement that is not in requirements.csv,
  - with --check: docs/traceability.md differs from what the current results produce.

Requirements verified on the physical stand (verification "stand") are listed as NOT VERIFIED
until someone adds measured results; they never count as passed.

  python tools/trace.py --c-results c_results.txt --junit pytest_results.xml --check
"""

import argparse
import csv
import sys
import xml.etree.ElementTree as ET
from collections import defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def load_requirements(path):
    with open(path, newline="", encoding="utf-8") as f:
        return list(csv.DictReader(f))


def load_c_results(path):
    results = []
    for line in Path(path).read_text(encoding="utf-8").splitlines():
        if not line.startswith("RESULT,"):
            continue
        _, case, reqs, verdict, checks = line.split(",")
        results.append({"id": case, "reqs": reqs.split(";"), "verdict": verdict, "checks": int(checks), "kind": "C"})
    return results


def load_junit(path):
    results = []
    root = ET.parse(path).getroot()
    for tc in root.iter("testcase"):
        reqs = []
        for prop in tc.iter("property"):
            if prop.get("name") == "req":
                reqs = [r for r in prop.get("value", "").split(",") if r]
        failed = any(c.tag in ("failure", "error") for c in tc)
        skipped = any(c.tag == "skipped" for c in tc)
        results.append({"id": tc.get("name"), "reqs": reqs, "verdict": "FAIL" if failed else ("SKIP" if skipped else "PASS"),
                        "checks": None, "kind": "pytest"})
    return results


def build(reqs, tests):
    known = {r["id"] for r in reqs}
    by_req = defaultdict(list)
    problems = []
    for t in tests:
        if not t["reqs"]:
            problems.append(f"test {t['id']} is not linked to any requirement")
        for rid in t["reqs"]:
            if rid not in known:
                problems.append(f"test {t['id']} names unknown requirement {rid}")
            by_req[rid].append(t)
        if t["verdict"] != "PASS":
            problems.append(f"test {t['id']} {t['verdict']}")

    rows, host_rows, stand_rows = [], [], []
    for r in reqs:
        ts = by_req.get(r["id"], [])
        if r["verification"] == "host":
            if not ts:
                status = "NO TEST"
                problems.append(f"{r['id']} is verified on the host but has no test")
            elif all(t["verdict"] == "PASS" for t in ts):
                status = "PASS"
            else:
                status = "FAIL"
            host_rows.append((r, ts, status))
        else:
            stand_rows.append(r)

    out = []
    out.append("# Requirements traceability matrix\n")
    out.append("Generated by `python tools/trace.py` from `tests/requirements.csv`, the C test output and the pytest results. "
               "CI regenerates it and fails if this file is out of date, a test fails, or a requirement has no test.\n")
    out.append("**What PASS means here:** the code passed its tests on a PC (gcc, pytest), several of them against a simulated plant. "
               "The test stand is not built, so nothing in this file is a measurement of real hardware.\n")
    n_pass = sum(1 for _, _, s in host_rows if s == "PASS")
    out.append(f"**Summary:** {n_pass} of {len(host_rows)} host-verifiable requirements pass; "
               f"{len(stand_rows)} requirements need the physical stand and are NOT VERIFIED.\n")
    out.append("## Requirements verified on the host\n")
    out.append("| Requirement | Level | Statement | Test cases | Result |")
    out.append("|---|---|---|---|---|")
    for r, ts, status in host_rows:
        names = ", ".join(t["id"] for t in ts) or "none"
        out.append(f"| {r['id']} | {r['level']} | {r['statement']} | {names} | {status} |")
    out.append("\n## Requirements that need the physical stand\n")
    out.append("| Requirement | Statement | Result |")
    out.append("|---|---|---|")
    for r in stand_rows:
        out.append(f"| {r['id']} | {r['statement']} | NOT VERIFIED (stand not built) |")
    out.append("\n## Test cases\n")
    out.append("| Test case | Kind | Requirements | Checks | Result |")
    out.append("|---|---|---|---|---|")
    for t in tests:
        checks = "" if t["checks"] is None else str(t["checks"])
        out.append(f"| {t['id']} | {t['kind']} | {', '.join(t['reqs'])} | {checks} | {t['verdict']} |")
    out.append("")
    return "\n".join(out), problems


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--requirements", default=str(ROOT / "tests" / "requirements.csv"))
    ap.add_argument("--c-results", required=True)
    ap.add_argument("--junit", required=True)
    ap.add_argument("--out", default=str(ROOT / "docs" / "traceability.md"))
    ap.add_argument("--check", action="store_true", help="fail if --out differs instead of rewriting it")
    a = ap.parse_args(argv)

    reqs = load_requirements(a.requirements)
    tests = load_c_results(a.c_results) + load_junit(a.junit)
    text, problems = build(reqs, tests)

    out = Path(a.out)
    if a.check:
        if not out.exists() or out.read_text(encoding="utf-8") != text:
            problems.append(f"{out.name} is out of date: run python tools/trace.py and commit the result")
    else:
        out.write_text(text, encoding="utf-8")
        print(f"wrote {out}")
    for p in problems:
        print("PROBLEM:", p)
    return 1 if problems else 0


if __name__ == "__main__":
    sys.exit(main())
